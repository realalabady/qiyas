/**
 * The long-form intro for a quiz: whatever an editor wrote in the admin panel,
 * otherwise the repo-side fallback above.
 */
export function getQuizIntro(
  slug: unknown,
  authored?: unknown,
): string {
  const written = String(authored ?? "").trim();
  if (written) return written;
  return INTROS[String(slug ?? "").trim()] ?? "";
}
