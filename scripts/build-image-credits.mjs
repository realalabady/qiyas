/**
 * Generate src/data/image-credits.ts from the cover photo manifest.
 *
 * Unsplash's API terms require crediting the photographer and linking back to
 * their profile wherever one of their photographs is used. The covers are
 * composited, so there is nowhere on the image itself to put that — hence a
 * credits page, generated rather than hand-kept so it cannot drift away from
 * what is actually on the site.
 *
 * Titles are read out of the cover studio rather than duplicated here; a cover
 * whose title cannot be found is a hard error, because a silently missing
 * credit is the failure mode this file exists to prevent.
 *
 *   node scripts/build-image-credits.mjs
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const MANIFEST = path.join(ROOT, "scripts", "thumbnail-studio", "photos", "manifest.json");
const STUDIO = path.join(ROOT, "scripts", "thumbnail-studio", "covers.html");
const OUT = path.join(ROOT, "src", "data", "image-credits.ts");

if (!fs.existsSync(MANIFEST)) {
  console.error(`No manifest at ${MANIFEST} — run scripts/fetch-cover-photos.mjs first.`);
  process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
const studio = fs.readFileSync(STUDIO, "utf8");

function titleFor(key) {
  const re = new RegExp(
    `"${key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}"\\s*:\\s*\\{[^}]*?title:\\s*"([^"]+)"`,
    "s",
  );
  return re.exec(studio)?.[1] ?? null;
}

const rows = [];
const missing = [];
for (const [key, m] of Object.entries(manifest)) {
  const title = titleFor(key);
  if (!title) { missing.push(key); continue; }
  rows.push({
    // Photographic covers are JPEGs; see the note in set-thumbnails.ts.
    file: `/thumbnails/${key}.jpg`,
    title,
    photographer: m.photographer,
    photographerUrl: m.photographer_url,
    source: m.source,
    provider: m.provider,
  });
}

if (missing.length) {
  console.error("No title found in covers.html for: " + missing.join(", "));
  process.exit(1);
}

rows.sort((a, b) => a.file.localeCompare(b.file));

const body = `/**
 * GENERATED by scripts/build-image-credits.mjs — do not edit by hand.
 *
 * Attribution for the photographs behind the cover images. Unsplash's API
 * terms require the photographer to be credited with a link back, and the
 * covers are composited, so the credit lives on /image-credits instead.
 */

export interface ImageCredit {
  /** The composited cover this photograph sits behind. */
  file: string;
  /** Arabic headline on that cover, so a reader can tell which is which. */
  title: string;
  photographer: string;
  photographerUrl: string;
  source: string;
  provider: string;
}

export const IMAGE_CREDITS: ImageCredit[] = ${JSON.stringify(rows, null, 2)};
`;

fs.writeFileSync(OUT, body, "utf8");
console.log(`wrote ${rows.length} credit(s) to ${path.relative(ROOT, OUT)}`);
