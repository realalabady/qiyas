function loadEnv() {
  const file = path.join(process.cwd(), ".env.local");
  if (!fs.existsSync(file)) throw new Error(".env.local not found");
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (m && !process.env[m[1]]) {
      process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, "");
    }
  }
}

const wordCount = (s: unknown) =>
  String(s ?? "").trim().split(/\s+/).filter(Boolean).length;

async function main() {
  loadEnv();
  const app = initializeApp({
    apiKey: process.env.VITE_FIREBASE_API_KEY,
    authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN,
    projectId: process.env.VITE_FIREBASE_PROJECT_ID,
    storageBucket: process.env.VITE_FIREBASE_STORAGE_BUCKET,
    messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID,
    appId: process.env.VITE_FIREBASE_APP_ID,
  });

  let email = process.env.ADMIN_EMAIL;
  let password = process.env.ADMIN_PASSWORD;
  if (!email || !password) {
    const rl = readline.createInterface({ input: stdin, output: stdout });
    email ||= await rl.question("Admin email: ");
    password ||= await rl.question("Admin password: ");
    rl.close();
  }
  await signInWithEmailAndPassword(getAuth(app), email!, password!);
  const db = getFirestore(app);
  console.log(`Signed in as ${email}\n`);

  const snap = await getDocs(collection(db, "articles"));
  const docs = snap.docs.map((d) => ({ id: d.id, ...(d.data() as any) }));

  let applied = 0;
  for (const [slug, replacement] of Object.entries(ARTICLES)) {
    const target = docs.find((d) => String(d.slug ?? "").trim() === slug);
    if (!target) {
      console.log(`SKIP  slug not found: ${slug}`);
      continue;
    }
    console.log(
      `${String(target.title ?? "").trim().slice(0, 50)}\n` +
        `   ${wordCount(target.content)}w -> ${wordCount(replacement.content)}w` +
        (replacement.excerpt ? "  (+ new excerpt)" : ""),
    );
    if (!APPLY) continue;
    await updateDoc(doc(db, "articles", target.id), {
      content: replacement.content,
      ...(replacement.excerpt ? { excerpt: replacement.excerpt } : {}),
      updatedAt: new Date().toISOString(),
    });
    applied++;
  }

  if (!APPLY) {
    console.log("\nDry run — nothing written. Re-run with --apply.");
  } else {
    console.log(`\nUpdated ${applied} article(s).`);
  }
  // The Firebase client keeps its connection open and would hang the process.
  process.exit(0);
}

main().catch((e) => {
  console.error("\nFailed:", e?.message || e);
  process.exit(1);
});
